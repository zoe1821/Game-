#!/usr/bin/env python3
"""Feature registry tool for LIFEVERSE.

    feature_registry.py check     validate docs/feature_registry.json (exit 1 on any problem)
    feature_registry.py render    regenerate docs/FEATURE_REGISTRY.md from the JSON
    feature_registry.py selftest  prove that the checker rejects invalid entries

The JSON file is the single source of truth. The rules enforced here are the
project's completion protocol:

  PLANNED         specified; no code
  IN_DEVELOPMENT  being built; not complete
  IMPLEMENTED     code complete; no passing automated test recorded yet
  TESTED          automated tests exist and are listed in "tests"
  VERIFIED        TESTED-level evidence plus a reproducible verification procedure:
                  "verification" = {"how": command or procedure, "date": YYYY-MM-DD,
                  "commit": hash the check was run on, "result": observed outcome}
  BLOCKED         cannot progress; "blocked_reason" says why

A feature cannot be VERIFIED without a reproducible procedure, and every file
referenced under "tests" or "evidence" must exist in the repository.
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "feature_registry.json"
OUTPUT = ROOT / "docs" / "FEATURE_REGISTRY.md"
STATES = ["PLANNED", "IN_DEVELOPMENT", "IMPLEMENTED", "TESTED", "VERIFIED", "BLOCKED"]
LABEL = {"IN_DEVELOPMENT": "IN DEVELOPMENT"}
REQUIRED = ["id", "title", "area", "requirements", "milestone", "state"]
REQ_ID = re.compile(r"^(B\d{1,2}|A\d{1,2})$")


def load():
    return json.loads(SOURCE.read_text(encoding="utf-8"))


def check(data):
    problems = []
    areas = {a["id"] for a in data["areas"]}
    seen = set()
    for f in data["features"]:
        fid = f.get("id", "<missing id>")
        for key in REQUIRED:
            if key not in f:
                problems.append(f"{fid}: missing '{key}'")
        if fid in seen:
            problems.append(f"{fid}: duplicate id")
        seen.add(fid)
        if f.get("area") not in areas:
            problems.append(f"{fid}: unknown area '{f.get('area')}'")
        state = f.get("state")
        if state not in STATES:
            problems.append(f"{fid}: invalid state '{state}'")
        for r in f.get("requirements", []):
            if not REQ_ID.match(r):
                problems.append(f"{fid}: bad requirement id '{r}'")
        if not f.get("requirements"):
            problems.append(f"{fid}: no requirement reference")
        for rel in f.get("tests", []) + f.get("evidence", []):
            if not (ROOT / rel).exists():
                problems.append(f"{fid}: referenced file does not exist: {rel}")
        if state in ("TESTED", "VERIFIED") and not f.get("tests"):
            problems.append(f"{fid}: {state} requires a non-empty 'tests' list")
        if state == "VERIFIED":
            v = f.get("verification") or {}
            for key in ("how", "date", "commit", "result"):
                if not v.get(key):
                    problems.append(f"{fid}: VERIFIED requires verification.{key}")
        if state == "BLOCKED" and not f.get("blocked_reason"):
            problems.append(f"{fid}: BLOCKED requires 'blocked_reason'")
    return problems


def render(data):
    feats = data["features"]
    counts = Counter(f["state"] for f in feats)
    out = ["# LIFEVERSE — Feature Registry", "",
           "_Generated by `tools/feature_registry.py render` from `docs/feature_registry.json`."
           " Do not edit by hand._", "",
           f"Last updated: {data['updated']} · {len(feats)} features", "",
           "| State | Count | Meaning |", "|---|---|---|"]
    meaning = data["state_meanings"]
    for s in STATES:
        out.append(f"| {LABEL.get(s, s)} | {counts.get(s, 0)} | {meaning[s]} |")
    out += ["", "Requirement ids: `B<n>` = section n of the original brief, `A<n>` = section n of the"
            " additional requirements (both in `docs/requirements/`).", ""]
    for area in data["areas"]:
        rows = [f for f in feats if f["area"] == area["id"]]
        if not rows:
            continue
        out += [f"## {area['title']}", "", "| ID | Feature | Req. | Milestone | State | Evidence |",
                "|---|---|---|---|---|---|"]
        for f in rows:
            ev = ""
            if f["state"] == "VERIFIED":
                v = f["verification"]
                ev = f"`{v['how']}` — {v['result']} ({v['date']}, `{v['commit']}`)"
            elif f["state"] == "TESTED":
                ev = ", ".join(f"`{t}`" for t in f["tests"])
                if f.get("note"):
                    ev += f" — {f['note']}"
            elif f["state"] == "BLOCKED":
                ev = f["blocked_reason"]
            elif f.get("note"):
                ev = f["note"]
            out.append(f"| {f['id']} | {f['title']} | {' '.join(f['requirements'])} | {f['milestone']} |"
                       f" {LABEL.get(f['state'], f['state'])} | {ev} |")
        out.append("")
    return "\n".join(out)


def selftest():
    base = {"areas": [{"id": "a", "title": "A"}], "features": []}
    good = {"id": "X-1", "title": "t", "area": "a", "requirements": ["A1"], "milestone": "2", "state": "PLANNED"}
    cases = {
        "valid entry accepted": (dict(good), 0),
        "VERIFIED without tests or procedure": (dict(good, state="VERIFIED"), 5),
        "VERIFIED with tests but no procedure": (dict(good, state="VERIFIED", tests=["tools/feature_registry.py"]), 4),
        "TESTED without tests": (dict(good, state="TESTED"), 1),
        "missing test file": (dict(good, state="TESTED", tests=["tools/does_not_exist.sh"]), 1),
        "BLOCKED without reason": (dict(good, state="BLOCKED"), 1),
        "unknown state": (dict(good, state="DONE"), 1),
        "bad requirement id": (dict(good, requirements=["Z9"]), 1),
        "unknown area": (dict(good, area="zzz"), 1),
    }
    failed = 0
    for name, (entry, expected) in cases.items():
        got = len(check(dict(base, features=[entry])))
        ok = got == expected
        failed += 0 if ok else 1
        print(f"{'ok  ' if ok else 'FAIL'} {name}: {got} problem(s), expected {expected}")
    return 1 if failed else 0


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "selftest":
        return selftest()
    data = load()
    problems = check(data)
    if problems:
        print("\n".join(problems))
        print(f"{len(problems)} problem(s) in {SOURCE.name}")
        return 1
    if cmd == "render":
        OUTPUT.write_text(render(data), encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT)}")
    elif cmd == "check":
        if OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8") != render(data):
            print(f"{OUTPUT.name} is out of date; run: feature_registry.py render")
            return 1
        counts = Counter(f["state"] for f in data["features"])
        print(f"{len(data['features'])} features OK: " + ", ".join(f"{s}={counts.get(s, 0)}" for s in STATES))
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
